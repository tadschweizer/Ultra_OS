async (page) => {
  const errors = [];
  const requests = [];
  page.on('pageerror', err => errors.push(err.message));
  page.on('request', req => requests.push(req.url()));
  const passed = [];
  const check = (ok, label) => { if (!ok) throw new Error(label); passed.push(label); };
  const go = async hash => { await page.goto('http://127.0.0.1:4173/#' + hash); await page.locator('main h1').waitFor(); };
  const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('threshold-coach-research-v1')));
  await page.goto('http://127.0.0.1:4173');
  await page.evaluate(() => localStorage.removeItem('threshold-coach-research-v1'));
  await page.reload();
  await page.setViewportSize({width:1440,height:1000});
  check(await page.locator('.triage-row').count() === 3, 'Three initial triage items');
  await go('athletes');
  await page.getByRole('textbox',{name:'Search athletes'}).fill('maya');
  check(await page.locator('#roster-body tr').count() === 1, 'Roster search narrows athletes');
  await page.getByRole('textbox',{name:'Search athletes'}).fill('');
  await page.getByRole('combobox',{name:'Filter by group'}).selectOption('Trail & ultra');
  check(await page.locator('#roster-body tr').count() === 2, 'Group filter shows two trail athletes');
  await go('athlete/maya');
  await page.getByRole('button',{name:'Mark reviewed',exact:true}).click();
  check((await stored()).reviewed.includes('maya'), 'Review state is saved');
  await page.locator('#notes-form textarea').fill('Research note <script>unsafe()</script>');
  await page.getByRole('button',{name:'Save note',exact:true}).click();
  await page.reload();
  check(await page.locator('#notes-form textarea').inputValue() === 'Research note <script>unsafe()</script>', 'Notes survive reload and render literal markup');
  await go('calendar');
  await page.locator('button[data-action=workout][data-id="maya-3"]').click();
  check(await page.getByRole('dialog').isVisible(), 'Workout dialog opens');
  await page.locator('#workout-form [name=day]').selectOption('4');
  await page.locator('#workout-form [name=duration]').fill('40');
  await page.getByRole('button',{name:'Save workout',exact:true}).click();
  let s = await stored();
  check(s.workouts.find(w=>w.id==='maya-3').day === 4 && s.workouts.find(w=>w.id==='maya-3').duration === 40, 'Workout moved from Thursday to Friday');
  await page.locator('button[data-action=workout][data-id="maya-3"]').click();
  await page.locator('#comment-form textarea').fill('Friday works. Keep this one conversational. <b>Literal text</b>');
  await page.getByRole('button',{name:'Add comment',exact:true}).click();
  check(await page.locator('#workout-comments').innerText().then(t=>t.includes('<b>Literal text</b>')), 'Workout comment renders safely as text');
  await page.keyboard.press('Escape');
  check(!(await page.getByRole('dialog').isVisible()), 'Dialog closes with Escape');
  await page.getByRole('button',{name:'Next week',exact:true}).click();
  check(await page.locator('.workout').count() === 0, 'Next week starts empty');
  await page.getByRole('button',{name:'Add workout',exact:false}).first().click();
  await page.locator('#workout-form [name=title]').fill('Research easy session');
  await page.locator('#workout-form [name=duration]').fill('25');
  await page.getByRole('button',{name:'Save workout',exact:true}).click();
  check(await page.locator('.workout').count() === 1, 'Create session in another week');
  await go('messages/maya');
  await page.getByRole('button',{name:'Schedule adjustment',exact:true}).click();
  check((await page.locator('#message-form textarea').inputValue()).includes('Which days work best'), 'Editable message template');
  await page.locator('#message-form textarea').fill('Moved your session to Friday. Let me know how it feels.');
  await page.getByRole('button',{name:'Send in demo',exact:false}).click();
  check((await stored()).messages.maya.at(-1).body.includes('Friday'), 'Message saved to correct athlete');
  await go('messages/eli');
  check(!(await page.locator('#chat-log').innerText()).includes('Moved your session'), 'Athlete conversations stay separate');
  await go('library');
  await page.locator('[data-action=assign-template][data-id=easy]').click();
  await page.locator('#workout-form [name=athlete]').selectOption('nora');
  await page.getByRole('button',{name:'Save workout',exact:true}).click();
  check((await stored()).workouts.some(w=>w.athlete==='nora' && w.week===1 && w.title==='Easy aerobic run'), 'Library assignment creates an editable calendar session');
  await go('insights');
  await page.getByRole('button',{name:'Add protocol',exact:false}).first().click();
  await page.locator('#protocol-form [name=title]').fill('Recovery routine');
  await page.locator('#protocol-form [name=detail]').fill('Log sleep and energy for one sample week.');
  await page.getByRole('button',{name:'Assign in demo',exact:true}).click();
  check((await stored()).protocols.at(-1).title==='Recovery routine', 'Protocol assignment saved');
  await go('preview/maya');
  await page.locator('[data-action=complete][data-id="maya-3"]').click();
  check((await stored()).workouts.find(w=>w.id==='maya-3').done, 'Athlete completion updates shared demo state');
  await go('feedback');
  await page.locator('[name=tools]').fill('TrainingPeaks for plans; email for messages.');
  await page.locator('[name=context]').fill('Six recreational runners');
  await page.locator('[name=feature1]').selectOption('Would use regularly');
  await page.reload();
  check(await page.locator('[name=tools]').inputValue()==='TrainingPeaks for plans; email for messages.', 'Feedback autosaves across refresh');
  await page.evaluate(() => { const original=URL.createObjectURL;URL.createObjectURL=blob=>{window.exportedDemoBlob=blob;return original.call(URL,blob);}; });
  const firstDownload=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download feedback',exact:false}).click();
  const download=await firstDownload;
  check(download.suggestedFilename()==='threshold-coach-feedback.txt', 'Readable feedback filename');
  await download.saveAs('output/coach-demo/feedback-without-usage.txt');
  let exported=await page.evaluate(()=>window.exportedDemoBlob.text());
  check(exported.includes('TrainingPeaks for plans') && !exported.includes('LOCAL DEMO USAGE'), 'Feedback export includes answers, excludes usage by default');
  await page.locator('[name=includeUsage]').check();
  const secondDownload=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download feedback',exact:false}).click();
  await (await secondDownload).saveAs('output/coach-demo/feedback-with-usage.txt');
  exported=await page.evaluate(()=>window.exportedDemoBlob.text());
  check(exported.includes('LOCAL DEMO USAGE')&&exported.includes('edit_workout'), 'Usage included only after participant opts in');
  for(const width of [390,320]){
    await page.setViewportSize({width,height:844});
    for(const hash of ['overview','athletes','calendar','messages/maya','library','insights','feedback','guide','athlete/maya','preview/maya']){
      await go(hash);
      const fit=await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth);
      check(fit, `${width}px layout fits: ${hash}`);
    }
  }
  await go('overview');
  await page.screenshot({path:'output/coach-demo/mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Reset demo',exact:true}).click();
  await page.getByRole('button',{name:'Keep exploring',exact:true}).click();
  check((await stored()).feedback.tools?.includes('TrainingPeaks'), 'Cancel reset preserves answers');
  await page.getByRole('button',{name:'Reset demo',exact:true}).click();
  await page.getByRole('button',{name:'Reset sample data',exact:true}).click();
  s=await stored();
  check(s.workouts.length===24 && !s.feedback.tools && !s.reviewed.length, 'Confirm reset restores original sample state');
  await page.screenshot({path:'output/coach-demo/desktop.png',fullPage:true});
  check(errors.length===0,'No browser JavaScript errors');
  check(requests.every(u=>u.startsWith('http://127.0.0.1:4173/')||u.startsWith('blob:')),'No requests to remote services');
  return {passed:passed.length,checks:passed,errors};
}
