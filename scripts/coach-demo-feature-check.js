async (page) => {
  const passed=[],errors=[],requests=[];
  page.on('pageerror',err=>errors.push(err.message));
  page.on('request',r=>requests.push(r.url()));
  const check=(ok,label)=>{if(!ok)throw new Error(label);passed.push(label);};
  const go=async hash=>{await page.goto('http://127.0.0.1:4173/#'+hash);await page.locator('main h1').waitFor();};
  const state=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('threshold-coach-research-v1')));
  await page.setViewportSize({width:1440,height:1000});
  await go('overview');
  check(await page.locator('#nav .nav-section').count()===6,'Product navigation groups');
  await page.getByRole('tab',{name:'Load Trends',exact:true}).click();
  check(await page.locator('main .chart').count()===6,'Load Trends covers the roster');
  await page.getByRole('tab',{name:'Notes',exact:true}).click();
  check(await page.locator('main').innerText().then(t=>t.includes('Edit coaching notes')),'Notes workspace');
  await page.getByRole('tab',{name:'Alerts',exact:true}).click();
  check(await page.locator('.alert-row').count()===3,'Alerts workspace');
  await page.getByRole('tab',{name:'Advanced',exact:true}).click();
  await page.getByRole('tab',{name:'Templates',exact:true}).click();
  check(await page.locator('main').innerText().then(t=>t.includes('Shared documents')),'Advanced template and document workspace');
  await page.getByRole('button',{name:'Share document',exact:true}).click();
  await page.locator('#x-document-form [name=athlete]').selectOption('maya');
  await page.locator('#x-document-form [name=title]').fill('Research warm-up');
  await page.locator('#x-document-form [name=body]').fill('Fictional text <script>literal()</script>');
  await page.getByRole('button',{name:'Share in demo',exact:true}).click();
  const doc=(await state()).documents.at(-1);
  await go('athlete/maya');
  await page.locator('[data-action=x-open-document][data-id="'+doc.id+'"]').click();
  check(await page.getByRole('dialog').innerText().then(t=>t.includes('<script>literal()</script>')),'Shared documents appear in athlete file as literal text');
  await page.keyboard.press('Escape');
  await go('overview');
  await page.getByRole('button',{name:'Invite an athlete',exact:true}).click();
  await page.locator('#x-invite-form [name=name]').fill('Fictional Athlete');
  await page.getByRole('button',{name:'Create sample invitation',exact:true}).click();
  check(await page.getByRole('dialog').innerText().then(t=>t.includes('No email was sent')),'Invitation preview has honest delivery state');
  await page.keyboard.press('Escape');
  await go('groups');
  await page.locator('#x-group-form [name=name]').fill('Research test group');
  await page.locator('#x-group-form [value=maya]').check();
  await page.locator('#x-group-form [value=nora]').check();
  await page.getByRole('button',{name:'Create group',exact:true}).click();
  const group=(await state()).groups.at(-1);
  check(group.members.length===2,'Create group with selected athletes');
  await page.locator('#x-group-workout-form [name=group]').selectOption(group.id);
  await page.locator('#x-group-workout-form [name=template]').selectOption('strength');
  await page.getByRole('button',{name:'Assign workout',exact:true}).click();
  check((await state()).workouts.filter(w=>w.id.startsWith('group-workout')).length===2,'Group workout assignment creates both sessions');
  await page.locator('#x-group-protocol-form [name=group]').selectOption(group.id);
  await page.getByRole('button',{name:'Assign protocol',exact:true}).click();
  check((await state()).protocols.filter(p=>p.detail.startsWith('Sample group')).length===2,'Group protocol assignment');
  await go('tools');
  check(await page.locator('.tool-card').count()===7,'All seven product calculators');
  check((await page.locator('#result-hr').innerText()).includes('143–150 bpm'),'Threshold HR zones match sample product inputs');
  await page.locator('[data-tool=hr] [name=method]').selectOption('max');
  await page.locator('[data-tool=hr] [name=max]').fill('200');
  check((await page.locator('#result-hr').innerText()).includes('120–140 bpm'),'Maximum HR method recalculates');
  await page.locator('[data-tool=power] [name=ftp]').fill('300');
  check((await page.locator('#result-power').innerText()).includes('168–225 W'),'Power zones recalculate');
  check((await page.locator('#result-swim').innerText()).includes('1:39/100m'),'Swim CSS matches product formula');
  await page.locator('[data-tool=converter] [name=distance]').fill('10');
  await page.locator('[data-tool=converter] [name=unit]').selectOption('km');
  await page.locator('[data-tool=converter] [name=time]').fill('50:00');
  check((await page.locator('#result-converter').innerText()).includes('5:00'),'Pace converter recalculates');
  check((await page.locator('#result-ramp').innerText()).includes('403'),'Ramp planner matches product formula');
  await page.locator('[data-tool=swim] [name=t400]').fill('bad');
  check((await page.locator('#result-swim').innerText()).includes('valid inputs'),'Invalid calculator input handled');
  await go('races');
  await page.getByRole('button',{name:'Add race',exact:false}).click();
  await page.locator('#x-race-form [name=name]').fill('Fictional Fall 10K');
  await page.getByRole('button',{name:'Save race',exact:true}).click();
  const race=(await state()).races.at(-1);
  check(race.name==='Fictional Fall 10K','New target race saved');
  await page.locator('[data-action=x-blueprint][data-id="'+race.id+'"]').click();
  await page.locator('#x-blueprint-form [name=strategy]').fill('Sample coach-written pacing strategy');
  await page.getByRole('button',{name:'Save blueprint',exact:true}).click();
  check((await state()).races.at(-1).strategy.includes('coach-written'),'Blueprint saved against selected race');
  await go('log-intervention');
  await page.locator('#x-intervention-form [name=notes]').fill('Sample intervention observation');
  await page.getByRole('button',{name:'Save intervention',exact:true}).click();
  await page.waitForURL('**/#history');
  await page.getByRole('heading',{name:'Intervention History',exact:true}).waitFor();
  check((await page.locator('main').innerText()).includes('Sample intervention observation'),'Intervention appears in history');
  await go('check-in');
  await page.locator('#x-checkin-form [name=athlete]').selectOption('maya');
  await page.locator('#x-checkin-form [name=note]').fill('Sample updated daily check-in');
  await page.getByRole('button',{name:'Save check-in',exact:true}).click();
  check((await state()).checkins.maya.note==='Sample updated daily check-in','Daily check-in saved for athlete');
  await go('research');
  await page.locator('[data-action=x-bookmark]').first().click();
  await page.getByRole('tab',{name:/Saved/}).click();
  check(await page.locator('.resource-entry').count()===1,'Saved research filter');
  await go('account');
  await page.locator('#x-profile-form [name=display_name]').fill('Alex Sample Coaching');
  await page.getByRole('button',{name:'Save profile',exact:true}).click();
  await go('overview');
  check((await page.locator('main h1').innerText())==='Alex Sample Coaching','Profile updates Command Center');
  await go('notifications');
  await page.locator('[name=messages]').uncheck();
  await page.getByRole('button',{name:'Save preferences',exact:true}).click();
  await page.reload();
  check(!(await page.locator('[name=messages]').isChecked()),'Notification preference persists');
  const routes=['overview','athletes','calendar','messages/maya','library','tools','groups','dashboard','races','race-plan','check-in','log-intervention','history','insights','progress','explorer','research','connections','settings','account','notifications','pricing','support','guide','feedback','athlete/maya','preview/maya'];
  for(const width of [390,320]){await page.setViewportSize({width,height:844});for(const r of routes){await go(r);check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),width+'px fits: '+r);}}
  await page.getByRole('button',{name:'More',exact:true}).click();
  check(await page.getByRole('dialog').getByRole('link',{name:'Coach Tools',exact:true}).isVisible(),'Mobile More exposes full product navigation');
  await page.keyboard.press('Escape');
  await go('overview');
  await page.screenshot({path:'output/coach-demo/mobile-v2.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Reset demo',exact:true}).click();
  await page.getByRole('button',{name:'Reset sample data',exact:true}).click();
  check((await state()).groups.length===3 && (await state()).races.length===3,'Reset restores new feature fixtures');
  await page.screenshot({path:'output/coach-demo/desktop-v2.png',fullPage:true});
  check(errors.length===0,'No JavaScript errors across expanded pages');
  check(requests.every(r=>r.startsWith('http://127.0.0.1:4173/')||r.startsWith('blob:')),'No remote application requests');
  return {passed:passed.length,checks:passed,errors};
}
